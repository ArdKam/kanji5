import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const js=read('v2-presentation.js');
const css=read('v2-presentation.css');
const manifest=JSON.parse(read('manifest.webmanifest'));
for(const token of ['کانجی ۵','یادآوری فعال','پاسخ شما','بررسی پاسخ','نمی‌دانم','تمرین بعدی','جزئیات جلسه','مهارت‌های یادگیرنده','تمرکز تطبیقی','خلاصه جلسه','نتایج اخیر']) assert.ok(js.includes(token),token);
for(const token of ['دیده نشده','ضعیف','در حال بازیابی','مسلط','ترمیم','تقویت','بازیابی','حفظ','اکتشاف','پاسخ درست']) assert.ok(js.includes(token),token);
assert.ok(css.includes('direction:rtl'));
assert.ok(css.includes('direction:ltr'));
assert.equal(manifest.lang,'fa');
assert.equal(manifest.dir,'rtl');
assert.equal(manifest.theme_color,'#4f46e5');
console.log('Kanji 5 v2 localization and typography contract passed.');
